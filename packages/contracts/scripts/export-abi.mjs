// Writes the contract ABIs the web app and the MCP server need into packages/core/src/abi.ts.
// Run after `hardhat compile`:  node scripts/export-abi.mjs
//
// To keep the website small the ABIs are trimmed: `internalType` fields (used only by code generators) are
// dropped, and so are events the app never reads. Functions and errors are kept whole, so every call can be
// encoded and every revert reason decoded.
import fs from 'node:fs';

const names = ['Gavelock', 'TenderPanel', 'TenderRecords', 'RuleStock'];
// Events the audit pack looks up by name, per contract.
const keepEvents = { Gavelock: ['TenderCreated', 'BidSealed', 'Awarded', 'Cancelled', 'Finalized'], TenderRecords: ['DocumentPublished'], TenderPanel: [], RuleStock: [] };

const strip = (value) => {
  if (Array.isArray(value)) return value.map(strip);
  if (value && typeof value === 'object') {
    const out = {};
    for (const [k, v] of Object.entries(value)) if (k !== 'internalType') out[k] = strip(v);
    return out;
  }
  return value;
};

const out = ['// Generated by packages/contracts/scripts/export-abi.mjs from the compiled contracts. Do not edit.', ''];
for (const name of names) {
  const artifact = JSON.parse(fs.readFileSync(new URL(`../artifacts/contracts/${name}.sol/${name}.json`, import.meta.url), 'utf8'));
  const abi = strip(artifact.abi.filter((item) => item.type !== 'event' || keepEvents[name].includes(item.name)));
  const lower = name[0].toLowerCase() + name.slice(1);
  out.push(`export const ${lower}Abi = ${JSON.stringify(abi)} as const;`, '');
}
fs.writeFileSync(new URL('../../core/src/abi.ts', import.meta.url), out.join('\n'));
console.log('wrote packages/core/src/abi.ts');
